use std::ffi::{OsStr, OsString};
use std::fs;
use std::path::Path;

use portable_pty::CommandBuilder;

use crate::config::write_private_file;

const ZSH_DIR: &str = "shell-integration/zsh";
const ZSH_SCRIPT_NAME: &str = "zu-term.zsh";
const ZSH_INTEGRATION: &str = include_str!("../../../../../shell/osc7.zsh");
const BASH_DIR: &str = "shell-integration/bash";
const BASH_SCRIPT_NAME: &str = "zu-term.bash";
const BASH_RCFILE_NAME: &str = "rcfile.bash";
const BASH_INTEGRATION: &str = include_str!("../../../../../shell/zu-term.bash");
const FISH_DIR: &str = "shell-integration/fish";
const FISH_VENDOR_REL: &str = "fish/vendor_conf.d";
const FISH_SCRIPT_NAME: &str = "zu-term.fish";
const FISH_INTEGRATION: &str = include_str!("../../../../../shell/zu-term.fish");
// zsh reads `.zshenv` from ZDOTDIR first. It hands ZDOTDIR back to the user
// before any of their files run, so `.zprofile`/`.zshrc` load as usual.
const ZSHENV: &str = r#"# Generated by Zu Term: restores the user's ZDOTDIR and loads its integration.
_zu_term_integration=$ZDOTDIR/zu-term.zsh
if [[ -n ${ZU_TERM_USER_ZDOTDIR+x} ]]; then
  export ZDOTDIR=$ZU_TERM_USER_ZDOTDIR
else
  unset ZDOTDIR
fi
unset ZU_TERM_USER_ZDOTDIR
export skip_global_compinit=1
zsh-newuser-install() { :; }
[[ -r ${ZDOTDIR:-$HOME}/.zshenv ]] && source ${ZDOTDIR:-$HOME}/.zshenv
[[ -o interactive && -r $_zu_term_integration ]] && source $_zu_term_integration
unset _zu_term_integration
"#;

// bash skips its startup files when launched with --rcfile, so this wrapper
// loads them as a login shell would (the profile, which usually sources
// `.bashrc`; `.bashrc` only without a profile) and then Zu Term's hooks.
const BASH_RCFILE: &str = r#"# Generated by Zu Term: loads user bash startup files and Zu Term integration.
[[ -r /etc/profile ]] && source /etc/profile
if [[ -r "$HOME/.bash_profile" ]]; then
  source "$HOME/.bash_profile"
elif [[ -r "$HOME/.bash_login" ]]; then
  source "$HOME/.bash_login"
elif [[ -r "$HOME/.profile" ]]; then
  source "$HOME/.profile"
elif [[ -r "$HOME/.bashrc" ]]; then
  source "$HOME/.bashrc"
fi
[[ -n "${ZU_TERM_BASH_INTEGRATION:-}" && -r "$ZU_TERM_BASH_INTEGRATION" ]] && source "$ZU_TERM_BASH_INTEGRATION"
unset ZU_TERM_BASH_INTEGRATION
"#;

fn install(directory: &Path, name: &str, data: &str) -> Result<(), String> {
    if fs::read_to_string(directory.join(name)).is_ok_and(|current| current == data) {
        return Ok(());
    }
    write_private_file(directory, name, data)
}

/// Loads the bundled shell integration into zsh, bash or fish without editing
/// the user's dotfiles. Other shells are left untouched.
pub fn apply(command: &mut CommandBuilder, shell: &str, config: &Path) -> Result<(), String> {
    match Path::new(shell).file_name().and_then(OsStr::to_str) {
        Some("zsh") => {
            let directory = config.join(ZSH_DIR);
            install(&directory, ZSH_SCRIPT_NAME, ZSH_INTEGRATION)?;
            install(&directory, ".zshenv", ZSHENV)?;
            if let Some(user_zdotdir) = command.get_env("ZDOTDIR").map(OsStr::to_owned) {
                command.env("ZU_TERM_USER_ZDOTDIR", user_zdotdir);
            }
            command.env("ZDOTDIR", directory);
        }
        Some("bash") => {
            let directory = config.join(BASH_DIR);
            install(&directory, BASH_SCRIPT_NAME, BASH_INTEGRATION)?;
            install(&directory, BASH_RCFILE_NAME, BASH_RCFILE)?;
            command.env("ZU_TERM_BASH_INTEGRATION", directory.join(BASH_SCRIPT_NAME));
            if command.is_default_prog() {
                let argv = command.get_argv_mut();
                argv.push(OsString::from(shell));
                argv.push(OsString::from("--rcfile"));
                argv.push(directory.join(BASH_RCFILE_NAME).into_os_string());
            }
        }
        Some("fish") => {
            let root = config.join(FISH_DIR);
            let vendor = root.join(FISH_VENDOR_REL);
            install(&vendor, FISH_SCRIPT_NAME, FISH_INTEGRATION)?;
            let tail = match command.get_env("XDG_DATA_DIRS").map(OsStr::to_owned) {
                Some(existing) if !existing.is_empty() => {
                    command.env("ZU_TERM_USER_XDG_DATA_DIRS", &existing);
                    existing
                }
                _ => OsString::from("/usr/local/share:/usr/share"),
            };
            let mut joined = root.into_os_string();
            joined.push(":");
            joined.push(tail);
            command.env("XDG_DATA_DIRS", joined);
        }
        _ => {}
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::sync::mpsc;
    use std::time::Duration;

    use portable_pty::CommandBuilder;

    use super::{BASH_DIR, FISH_DIR, ZSH_DIR, apply};
    use crate::config::test_dir;
    use crate::pty::registry::{PtyEvent, PtyRegistry};

    fn run(command: CommandBuilder) -> String {
        let registry = PtyRegistry::default();
        let (tx, rx) = mpsc::channel();
        registry
            .spawn("main", command, 200, 24, move |event| {
                let _ = tx.send(event);
            })
            .expect("spawn");
        let mut output = Vec::new();
        loop {
            match rx.recv_timeout(Duration::from_secs(20)) {
                Ok(PtyEvent::Output(bytes)) => output.extend(bytes),
                Ok(PtyEvent::Exit(_)) => return String::from_utf8_lossy(&output).into(),
                Err(err) => panic!(
                    "pty event timed out ({err:?}). Output received so far: {:?}",
                    String::from_utf8_lossy(&output)
                ),
            }
        }
    }

    #[test]
    fn leaves_unsupported_shells_untouched() {
        let config = test_dir("integration-sh");
        let mut command = CommandBuilder::new("/bin/sh");
        apply(&mut command, "/bin/sh", &config).expect("apply");
        assert_eq!(command.get_env("ZDOTDIR"), None);
        assert_eq!(command.get_env("XDG_DATA_DIRS"), None);
        assert!(!config.exists());
    }

    #[test]
    fn configures_bash_integration_with_private_rcfile_for_default_prog() {
        let config = test_dir("integration-bash");
        let mut command = CommandBuilder::new_default_prog();
        apply(&mut command, "/bin/bash", &config).expect("apply");

        let directory = config.join(BASH_DIR);
        let rcfile = directory.join("rcfile.bash");
        assert!(rcfile.is_file());
        assert!(directory.join("zu-term.bash").is_file());
        let argv = command.get_argv();
        assert_eq!(argv.len(), 3);
        assert_eq!(argv[0], "/bin/bash");
        assert_eq!(argv[1], "--rcfile");
        assert_eq!(argv[2], rcfile.as_os_str());
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = fs::metadata(&rcfile).expect("meta").permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }
        fs::remove_dir_all(config).expect("cleanup");
    }

    #[test]
    fn configures_fish_integration_via_xdg_data_dirs_and_preserves_existing() {
        let config = test_dir("integration-fish");
        let mut command = CommandBuilder::new_default_prog();
        command.env("XDG_DATA_DIRS", "/custom/share:/usr/share");
        apply(&mut command, "/usr/bin/fish", &config).expect("apply");

        let directory = config.join(FISH_DIR);
        let script = directory.join("fish/vendor_conf.d/zu-term.fish");
        assert!(script.is_file());
        assert_eq!(
            command.get_env("ZU_TERM_USER_XDG_DATA_DIRS"),
            Some("/custom/share:/usr/share".as_ref())
        );
        let xdg = command.get_env("XDG_DATA_DIRS").and_then(|v| v.to_str()).unwrap_or("");
        assert!(xdg.starts_with(&format!("{}:", directory.display())), "xdg was {xdg:?}");
        assert!(xdg.ends_with("/custom/share:/usr/share"));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = fs::metadata(&script).expect("meta").permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }
        fs::remove_dir_all(config).expect("cleanup");
    }

    #[test]
    fn points_zsh_to_private_integration_files_and_keeps_the_user_zdotdir() {
        let config = test_dir("integration-files");
        let mut command = CommandBuilder::new("zsh");
        command.env("ZDOTDIR", "/Users/me/.zsh");
        apply(&mut command, "/bin/zsh", &config).expect("apply");

        let directory = config.join(ZSH_DIR);
        assert_eq!(command.get_env("ZDOTDIR"), Some(directory.as_os_str()));
        assert_eq!(command.get_env("ZU_TERM_USER_ZDOTDIR"), Some("/Users/me/.zsh".as_ref()));
        assert!(directory.join(".zshenv").is_file());
        assert!(directory.join("zu-term.zsh").is_file());
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = fs::metadata(directory.join(".zshenv")).expect("meta").permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }
        fs::remove_dir_all(config).expect("cleanup");
    }

    #[test]
    fn an_interactive_zsh_loads_the_user_files_and_the_integration() {
        let root = test_dir("integration-zsh");
        let home = root.join("home");
        fs::create_dir_all(&home).expect("home");
        fs::write(home.join(".zshenv"), "export USER_ENV=env\n").expect("zshenv");
        fs::write(home.join(".zshrc"), "export USER_RC=rc\n").expect("zshrc");

        let mut command = CommandBuilder::new("zsh");
        // `+m` disables job control (MONITOR) so zsh doesn't try to manipulate
        // foreground process groups with tcsetpgrp(), which causes SIGTTIN/SIGTTOU
        // hangs in automated headless PTY environments like Linux CI.
        command.args([
            "-i",
            "+m",
            "-c",
            "print -r -- \"result=$USER_ENV:$USER_RC:${+functions[_zu_term_osc7]}:${ZDOTDIR-unset}\"",
        ]);
        command.env("HOME", &home);
        command.env_remove("ZDOTDIR");
        command.env("skip_global_compinit", "1");
        apply(&mut command, "zsh", &root.join("config")).expect("apply");

        let output = run(command);
        assert!(output.contains("result=env:rc:1:unset"), "output was {output:?}");
        fs::remove_dir_all(root).expect("cleanup");
    }

    // Like the login shell Zu Term used to start: the profile only, and
    // `.bashrc` when no profile exists. Most profiles source `.bashrc` already.
    #[test]
    fn an_interactive_bash_runs_bashrc_once_when_the_profile_sources_it() {
        let root = test_dir("integration-bash-profile");
        let home = root.join("home");
        fs::create_dir_all(&home).expect("home");
        fs::write(home.join(".bash_profile"), "source \"$HOME/.bashrc\"\n").expect("profile");
        fs::write(home.join(".bashrc"), "RC_COUNT=$((RC_COUNT + 1))\n").expect("bashrc");

        let config = root.join("config");
        let mut bootstrap = CommandBuilder::new_default_prog();
        apply(&mut bootstrap, "/bin/bash", &config).expect("apply");
        let rcfile = config.join(BASH_DIR).join("rcfile.bash");

        let mut command = CommandBuilder::new("/bin/bash");
        command.args([
            "--rcfile",
            rcfile.to_str().expect("utf8 rcfile"),
            "-i",
            "+m",
            "-c",
            "printf 'result=%s\\n' \"$RC_COUNT\"",
        ]);
        command.env("HOME", &home);

        let output = run(command);
        assert!(output.contains("result=1"), "output was {output:?}");
        fs::remove_dir_all(root).expect("cleanup");
    }

    #[test]
    fn an_interactive_bash_loads_user_bashrc_and_integration() {
        let root = test_dir("integration-bash-pty");
        let home = root.join("home");
        fs::create_dir_all(&home).expect("home");
        fs::write(home.join(".bashrc"), "export USER_BASH_RC=ok\n").expect("bashrc");

        let config = root.join("config");
        let mut bootstrap = CommandBuilder::new_default_prog();
        apply(&mut bootstrap, "/bin/bash", &config).expect("apply");
        let rcfile = config.join(BASH_DIR).join("rcfile.bash");

        let mut command = CommandBuilder::new("/bin/bash");
        command.args([
            "--rcfile",
            rcfile.to_str().expect("utf8 rcfile"),
            "-i",
            "+m",
            "-c",
            "printf 'result=%s:%s\\n' \"$USER_BASH_RC\" \"$(type -t _zu_term_osc7)\"",
        ]);
        command.env("HOME", &home);
        command.env("ZU_TERM_BASH_INTEGRATION", config.join(BASH_DIR).join("zu-term.bash"));

        let output = run(command);
        assert!(output.contains("result=ok:function"), "output was {output:?}");
        fs::remove_dir_all(root).expect("cleanup");
    }
}
