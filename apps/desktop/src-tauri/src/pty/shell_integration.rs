use std::ffi::OsStr;
use std::fs;
use std::path::Path;

use portable_pty::CommandBuilder;

use crate::config::write_private_file;

const ZSH_DIR: &str = "shell-integration/zsh";
const ZSH_SCRIPT_NAME: &str = "zu-term.zsh";
const ZSH_INTEGRATION: &str = include_str!("../../../../../shell/osc7.zsh");
// zsh reads `.zshenv` from ZDOTDIR first. It hands ZDOTDIR back to the user
// before any of their files run, so `.zprofile`/`.zshrc` load as usual.
const ZSHENV: &str = r#"# Generated by Zu Term: restores the user's ZDOTDIR and loads its integration.
_zu_term_integration=$ZDOTDIR/zu-term.zsh
if [[ -n ${ZU_TERM_USER_ZDOTDIR+x} ]]; then
  export ZDOTDIR=$ZU_TERM_USER_ZDOTDIR
else
  unset ZDOTDIR
fi
unset ZU_TERM_USER_ZDOTDIR
[[ -r ${ZDOTDIR:-$HOME}/.zshenv ]] && source ${ZDOTDIR:-$HOME}/.zshenv
[[ -o interactive && -r $_zu_term_integration ]] && source $_zu_term_integration
unset _zu_term_integration
"#;

fn install(directory: &Path, name: &str, data: &str) -> Result<(), String> {
    if fs::read_to_string(directory.join(name)).is_ok_and(|current| current == data) {
        return Ok(());
    }
    write_private_file(directory, name, data)
}

/// Loads the bundled shell integration into zsh through ZDOTDIR, so it works
/// without editing `~/.zshrc`. Other shells are left untouched.
pub fn apply(command: &mut CommandBuilder, shell: &str, config: &Path) -> Result<(), String> {
    if Path::new(shell).file_name() != Some(OsStr::new("zsh")) {
        return Ok(());
    }
    let directory = config.join(ZSH_DIR);
    install(&directory, ZSH_SCRIPT_NAME, ZSH_INTEGRATION)?;
    install(&directory, ".zshenv", ZSHENV)?;
    if let Some(user_zdotdir) = command.get_env("ZDOTDIR").map(OsStr::to_owned) {
        command.env("ZU_TERM_USER_ZDOTDIR", user_zdotdir);
    }
    command.env("ZDOTDIR", directory);
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::sync::mpsc;
    use std::time::Duration;

    use portable_pty::CommandBuilder;

    use super::{ZSH_DIR, apply};
    use crate::config::test_dir;
    use crate::pty::registry::{PtyEvent, PtyRegistry};

    fn run(command: CommandBuilder) -> String {
        let registry = PtyRegistry::default();
        let (tx, rx) = mpsc::channel();
        registry
            .spawn("main", command, 200, 24, move |event| {
                let _ = tx.send(event);
            })
            .expect("spawn");
        let mut output = String::new();
        loop {
            match rx.recv_timeout(Duration::from_secs(10)).expect("pty event") {
                PtyEvent::Output(text) => output.push_str(&text),
                PtyEvent::Exit(_) => return output,
            }
        }
    }

    #[test]
    fn leaves_shells_other_than_zsh_untouched() {
        let config = test_dir("integration-bash");
        let mut command = CommandBuilder::new("/bin/bash");
        apply(&mut command, "/bin/bash", &config).expect("apply");
        assert_eq!(command.get_env("ZDOTDIR"), None);
        assert!(!config.exists());
    }

    #[test]
    fn points_zsh_to_private_integration_files_and_keeps_the_user_zdotdir() {
        let config = test_dir("integration-files");
        let mut command = CommandBuilder::new("zsh");
        command.env("ZDOTDIR", "/Users/me/.zsh");
        apply(&mut command, "/bin/zsh", &config).expect("apply");

        let directory = config.join(ZSH_DIR);
        assert_eq!(command.get_env("ZDOTDIR"), Some(directory.as_os_str()));
        assert_eq!(command.get_env("ZU_TERM_USER_ZDOTDIR"), Some("/Users/me/.zsh".as_ref()));
        assert!(directory.join(".zshenv").is_file());
        assert!(directory.join("zu-term.zsh").is_file());
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = fs::metadata(directory.join(".zshenv")).expect("meta").permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }
        fs::remove_dir_all(config).expect("cleanup");
    }

    #[test]
    fn an_interactive_zsh_loads_the_user_files_and_the_integration() {
        let root = test_dir("integration-zsh");
        let home = root.join("home");
        fs::create_dir_all(&home).expect("home");
        fs::write(home.join(".zshenv"), "export USER_ENV=env\n").expect("zshenv");
        fs::write(home.join(".zshrc"), "export USER_RC=rc\n").expect("zshrc");

        let mut command = CommandBuilder::new("zsh");
        command.args([
            "-i",
            "-c",
            "print -r -- \"result=$USER_ENV:$USER_RC:${+functions[_zu_term_osc7]}:${ZDOTDIR-unset}\"",
        ]);
        command.env("HOME", &home);
        command.env_remove("ZDOTDIR");
        apply(&mut command, "zsh", &root.join("config")).expect("apply");

        let output = run(command);
        assert!(output.contains("result=env:rc:1:unset"), "output was {output:?}");
        fs::remove_dir_all(root).expect("cleanup");
    }
}
